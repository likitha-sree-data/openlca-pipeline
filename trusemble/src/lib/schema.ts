// Single source of truth for the database schema. Applied idempotently on first connection.
export const SCHEMA_VERSION = 2;

const NOW = 'now_iso()';

/** Helpers every query can use: ISO-8601 UTC text timestamps, so dates sort and compare as plain text everywhere. */
export const FUNCTIONS = `
CREATE OR REPLACE FUNCTION now_iso() RETURNS text AS $$
  SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$ LANGUAGE sql STABLE;
CREATE OR REPLACE FUNCTION now_iso_minus(i interval) RETURNS text AS $$
  SELECT to_char((now() - i) AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$ LANGUAGE sql STABLE;
`;

