function seedDemo(rand: () => number, pick: <T>(a: readonly T[]) => T, demoSource: number) {
  const programs = all<{ id: number; name: string; ref: string | null }>(`SELECT id, name, source_ref ref FROM programs WHERE source_ref IS NOT NULL OR name LIKE 'FEMA%'`);
  const fedPrograms = programs.filter((p) => /FEMA|Cooperative|Defense|EQIP/.test(p.name));

  // county risk: high in the West and Southwest, lower elsewhere
  const westStates = new Set(['OR', 'CA', 'WA', 'ID', 'MT', 'CO', 'UT', 'NM', 'AZ', 'NV', 'WY']);
  const countyRows = DEMO_COUNTIES.map(([st, name, fips, lat, lng]) => {
    const risk = Math.round(((westStates.has(st) ? 55 : 15) + rand() * 45) * 10) / 10;
    run(`INSERT INTO counties (fips, name, state, lat, lng, risk_score, risk_rating, verification, source_id) VALUES (?, ?, ?, ?, ?, ?, ?, 'demo', ?)`,
      fips, name, st, lat, lng, risk, risk > 85 ? 'Very High' : risk > 70 ? 'Relatively High' : risk > 50 ? 'Relatively Moderate' : 'Relatively Low', demoSource);
    return { st, name, fips, lat, lng, risk };
  });

  const insertOrg = (name: string, type: string, c: (typeof countyRows)[number], jitter = 0.25) => {
    const lat = c.lat + (rand() - 0.5) * jitter * 2, lng = c.lng + (rand() - 0.5) * jitter * 2;
    return run(
      `INSERT INTO organizations (name, name_key, type, county, state, lat, lng, location_precision, published, verification, source_id)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, 'demo', ?)`,
      name, nameKey(name), type, `${c.name} County`, c.st, lat, lng, type === 'firewise_community' ? 'community' : 'county', demoSource,
    ).lastId;
  };

  const orgsByCounty = new Map<string, number[]>();
  for (const c of countyRows) {
    const ids: number[] = [];
    const nCommunities = westStates.has(c.st) ? 2 + Math.floor(rand() * 4) : 1 + Math.floor(rand() * 2);
    for (let i = 0; i < nCommunities; i++) ids.push(insertOrg(`(Demo) ${pick(PLACE_A)} ${pick(PLACE_B)}`, rand() < 0.85 ? 'firewise_community' : 'hoa', c));
    ids.push(insertOrg(`(Demo) ${c.name} County`, 'county', c, 0.05));
    if (rand() < 0.6) ids.push(insertOrg(`(Demo) ${c.name} Rural Fire Protection District`, 'fire_district', c));
    if (rand() < 0.3) ids.push(insertOrg(`(Demo) ${c.name} Resilience Partners`, 'nonprofit', c));
    orgsByCounty.set(c.fips, ids);
  }

  const west = countyRows.filter((x) => westStates.has(x.st));
  const east = countyRows.filter((x) => !westStates.has(x.st));
  const stagePick = () => { const r = rand(); return r < 0.58 ? 'complete' : r < 0.86 ? 'in_progress' : r < 0.94 ? 'funded' : r < 0.98 ? 'seeking_funding' : 'planning'; };
  const precPick = () => { const r = rand(); return r < 0.3 ? 'parcel' : r < 0.7 ? 'area_centre' : r < 0.9 ? 'community' : 'county'; };
  const projectIds: { id: number; fips: string; stage: string }[] = [];

  for (let i = 0; i < 520; i++) {
    const c = rand() < 0.85 ? pick(west) : pick(east);
    const w = pick(WORK);
    const owner = pick(orgsByCounty.get(c.fips)!);
    const place = `${pick(PLACE_A)} ${pick(PLACE_B)}`;
    const name = `(Demo) ${place} ${w}`;
    const stage = stagePick();
    const mapped = rand() > 0.045;
    const published = rand() > 0.03 ? 1 : 0;
    const lat = mapped ? c.lat + (rand() - 0.5) * 0.7 : null, lng = mapped ? c.lng + (rand() - 0.5) * 0.7 : null;
    const requested = stage === 'seeking_funding' ? Math.round((20 + rand() * 480) * 1000) : null;
    const id = run(
      `INSERT INTO projects (name, name_key, owner_org_id, stage, category, county, state, fips, lat, lng, location_precision, needs, requested_amount, published, verification, source_id)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'demo', ?)`,
      name, nameKey(name), owner, stage, CATEGORY_FOR[w], `${c.name} County`, c.st, c.fips, lat, lng, mapped ? precPick() : null,
      stage === 'seeking_funding' ? 'Funding' : null, requested, published, demoSource,
    ).lastId;
    projectIds.push({ id, fips: c.fips, stage });
  }

  // awards: most counties get some; a share of high-risk counties get none so the gap layer has something to show
  for (const c of countyRows) {
    const skip = c.risk > 70 ? rand() < 0.35 : rand() < 0.5;
    if (skip) continue;
    const n = 1 + Math.floor(rand() * 5);
    for (let i = 0; i < n; i++) {
      const prog = pick(fedPrograms);
      run(
        `INSERT INTO awards (program_id, org_id, amount_committed, amount_disbursed, year, county, state, fips, verification, source_id) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'demo', ?)`,
        prog.id, pick(orgsByCounty.get(c.fips)!), Math.round((15 + rand() * 900) * 1000), rand() < 0.6 ? Math.round((10 + rand() * 600) * 1000) : null,
        2021 + Math.floor(rand() * 6), `${c.name} County`, c.st, c.fips, demoSource,
      );
    }
  }
}
