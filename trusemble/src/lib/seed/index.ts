      headline: 'Seven neighborhoods asked', sub: 'and the answer was no',
      body: "Oregon's 2026 Small Forestland Grant round funded 11 of 112 applications. Seven from Deschutes County, filed by nine homeowner associations near Bend, Redmond and Sisters, were not among them. Their fuel-reduction plans are written. They need a funder.",
