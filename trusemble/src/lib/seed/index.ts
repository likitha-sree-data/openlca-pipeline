export type SeedOptions = { password?: string; demo?: boolean };

export function resetDatabase() {
  const d = db();
  d.exec('PRAGMA foreign_keys = OFF');
  const tables = all<{ name: string }>(`SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'`);
  for (const t of tables) d.exec(`DELETE FROM ${t.name}`);
  d.exec('PRAGMA foreign_keys = ON');
}

